import fs from 'node:fs';

const dir = 'packages/worker/migrations';
const files = fs.readdirSync(dir).filter((file) => file.endsWith('.sql')).sort();
const text = `// Generated by scripts/gen-migrations.mjs — do not edit by hand.
export const MIGRATION_FILES = ${JSON.stringify(files, null, 2)} as const;
`;
fs.writeFileSync('packages/worker/src/lib/migrations.generated.ts', text);
console.log(`wrote ${files.length} migration names`);
